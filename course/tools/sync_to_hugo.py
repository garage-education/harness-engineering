#!/usr/bin/env python3
"""Generate the Hugo course on a HugoBlox website from course/pages.

The course pages are the single source. This script writes
  <site>/content/<section>/agent-harness-spring-ai/
with one folder per part (_index.md) and one page per chapter, and installs
the diagram renderer: assets/js/house-diagrams.js, assets/css/house-diagrams.css,
and the body-end hook that loads both on the course pages only.

Usage:
  sync_to_hugo.py                      Garage Education: ~/Work/garage-education/website, content/docs
  sync_to_hugo.py SITE_DIR [--section docs] [--course-tag]

  --section      content folder under content/, also the URL prefix (docs -> /docs/...)
  --course-tag   tag the course root [Course], for sites whose course list filters on it

Re-run after every edit to course/pages. The course folder is replaced.
"""
import argparse
import json
import os
import re
import shutil
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
COURSE = os.path.dirname(HERE)
PAGES = os.path.join(COURSE, 'pages', 'course')
HUGO_FILES = os.path.join(COURSE, 'hugo')
SLUG = 'agent-harness-spring-ai'
DATE = '2026-10-10T00:00:00Z'
DOCS_JS = os.path.expanduser('~/.claude/skills/documentation/assets/site/docs.js')
DEFAULT_SITE = os.path.join(COURSE, '..', '..', '..', '..', 'garage-education', 'website')

COURSE_INDEX = """---
title: Building an Agent Harness with Spring AI
linktitle: Agent Harness with Spring AI
summary: Build the code around a large language model in Java. Tools, the agent loop, memory, hybrid retrieval, skills, sub-agents, evals, and durable execution with Temporal, one chapter at a time.
weight: 1
{tags}
date: "{date}"
lastmod: "{lastmod}"
draft: false
toc: true
---

## About "Building an Agent Harness with Spring AI"

This book teaches Java engineers to build an agent harness with Spring AI. The running example is the Log Incident Watcher. Read the chapters in order. Each chapter adds one idea. Run the code in each chapter before you read the next one. All examples use fake data and run offline.

## What you will build

{capstone_figure}

## Course Content

{contents}
"""

HOOK = """{{{{/* Diagram renderer for the "Building an Agent Harness with Spring AI" course.
     Loaded through the HugoBlox body-end hook, and only on that course's pages.
     Generated by GarageEducation/harness/course/tools/sync_to_hugo.py. */}}}}
{{{{ if strings.Contains .RelPermalink "{url_prefix}" }}}}
  {{{{ $css := resources.Get "css/house-diagrams.css" | minify | fingerprint "sha256" }}}}
  {{{{ $js := resources.Get "js/house-diagrams.js" | minify | fingerprint "sha256" }}}}
  <link rel="stylesheet" href="{{{{ $css.RelPermalink }}}}" integrity="{{{{ $css.Data.Integrity }}}}">
  <script src="{{{{ $js.RelPermalink }}}}" integrity="{{{{ $js.Data.Integrity }}}}"></script>
{{{{ end }}}}
"""


def read(path):
    text = open(path, encoding='utf-8').read()
    meta = {}
    m = re.match(r'^---\s*\n(.*?)\n---\s*\n', text, re.S)
    if m:
        for line in m.group(1).splitlines():
            k, _, v = line.partition(':')
            meta[k.strip()] = v.strip().strip('"')
        text = text[m.end():]
    return meta, text.lstrip('\n')


def prefix(name):
    return int(re.match(r'^(\d+)', name).group(1))


def stem(name):
    return os.path.splitext(name)[0]


def yaml_str(s):
    return json.dumps(s, ensure_ascii=False)   # a JSON string is a valid YAML scalar


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf-8').write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('site', nargs='?', default=DEFAULT_SITE)
    ap.add_argument('--section', default='docs')
    ap.add_argument('--course-tag', action='store_true')
    args = ap.parse_args()

    site = os.path.abspath(args.site)
    section = args.section.strip('/')
    url_section = section.split('/', 1)[1] if section.startswith('en/') else section   # content/en/x -> /x
    root = f'/{url_section}/{SLUG}'
    out = os.path.join(site, 'content', section, SLUG)

    def ref(path):
        return f'{{{{< relref "{root}/{path}" >}}}}'

    def hugo_body(body, group):
        # Links between course pages become relref, so Hugo checks them at build time.
        def link(m):
            target = m.group(1)
            path = target[3:] if target.startswith('../') else f'{group}/{target}'
            return f']({ref(path[:-5])})'
        body = re.sub(r'\]\(((?:\.\./)?[\w./-]+?\.html)\)', link, body)
        # Unknown facts stay visible, as in the standalone build.
        return re.sub(r'\[NEEDS INPUT:\s*([^\]]*)\]', r'<span class="needs-input">NEEDS INPUT: \1</span>', body)

    if os.path.isdir(out):
        shutil.rmtree(out)

    contents, capstone_figure, latest = [], '', 0
    for group in sorted(os.listdir(PAGES)):
        gdir = os.path.join(PAGES, group)
        if not os.path.isdir(gdir):
            continue
        g = json.load(open(os.path.join(gdir, '_group.json'), encoding='utf-8'))
        topics = []
        for name in sorted(n for n in os.listdir(gdir) if n.endswith('.md')):
            src = os.path.join(gdir, name)
            latest = max(latest, os.path.getmtime(src))
            meta, body = read(src)
            title = meta['title']
            fm = (f'---\ntitle: {yaml_str(title)}\nlinktitle: {yaml_str(meta.get("sidebar_label", title))}\n'
                  f'summary: {yaml_str(meta.get("description", ""))}\nweight: {prefix(name) * 10 + 10}\n\n'
                  f'date: "{DATE}"\ntoc: true\n---\n\n')
            write(os.path.join(out, group, name), fm + hugo_body(body, group))
            topics.append((title, f'{group}/{stem(name)}'))
            if group.startswith('07') and not capstone_figure:
                m = re.search(r'<figure class="arch">.*?</figure>', body, re.S)
                capstone_figure = m.group(0) if m else ''

        topic_list = '\n'.join(f'1. [{t}]({ref(p)})' for t, p in topics)
        write(os.path.join(out, group, '_index.md'),
              f'---\ntitle: {yaml_str(g["label"])}\nlinktitle: {yaml_str(g["label"])}\n'
              f'summary: {yaml_str(g.get("description", ""))}\nweight: {prefix(group) * 10 + 10}\n\n'
              f'date: "{DATE}"\ntoc: true\n---\n\n{g.get("description", "")}\n\n## Topics\n\n{topic_list}\n')
        contents.append(f'1. [{g["label"]}]({ref(group)})\n'
                        + '\n'.join(f'    1. [{t}]({ref(p)})' for t, p in topics))

    lastmod = datetime.fromtimestamp(latest, timezone.utc).strftime('%Y-%m-%dT00:00:00Z')
    write(os.path.join(out, '_index.md'), COURSE_INDEX.format(
        tags='tags: [Course]\n' if args.course_tag else '', date=DATE, lastmod=lastmod,
        capstone_figure=capstone_figure, contents='\n'.join(contents)))

    # Diagram renderer: the house docs.js without the page-shell behaviour
    # (table-of-contents spy and mobile menu belong to the standalone site).
    js = open(DOCS_JS, encoding='utf-8').read().replace('    tocSpy();\n    mobileMenu();\n', '')
    write(os.path.join(site, 'assets', 'js', 'house-diagrams.js'),
          '/* Generated by GarageEducation/harness/course/tools/sync_to_hugo.py from the documentation house style. Do not edit. */\n' + js)
    write(os.path.join(site, 'assets', 'css', 'house-diagrams.css'),
          open(os.path.join(HUGO_FILES, 'house-diagrams.css'), encoding='utf-8').read())
    write(os.path.join(site, 'layouts', '_partials', 'hooks', 'body-end', 'house-diagrams.html'),
          HOOK.format(url_prefix=f'{root}/'))
    print(f'Wrote {out} (URLs under {root}/)')


if __name__ == '__main__':
    main()
